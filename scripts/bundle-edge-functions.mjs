// ============================================================================
// bundle-edge-functions — produce copy/paste-ready Edge Function files.
//
// Supabase Edge Functions normally ship as a folder (`index.ts` + imports from
// `_shared/`). When you cannot use the Supabase CLI you must paste code into
// the dashboard's Edge Functions editor, which takes a SINGLE file per
// function. This script bundles each Tradovate function and its `_shared/*`
// imports into one self-contained ESM file.
//
// Output: docs/edge-functions/<name>.ts (one self-contained file per function).
// These ARE committed: the operator pastes them straight into the Supabase
// dashboard Edge Functions editor (no CLI available).
//
// Remote imports (https://deno.land/..., jsr:, npm:) are left EXTERNAL because
// the Deno runtime resolves them at deploy time.
//
// Usage: node scripts/bundle-edge-functions.mjs
// ============================================================================

import { build } from 'esbuild';
import fs from 'fs';
import path from 'path';

const FUNCTIONS = [
  'tradovate-connect',
  'tradovate-dashboard',
  'tradovate-data',
  'tradovate-disconnect',
  'tradovate-status',
  'tradovate-sync',
];

const OUT = 'docs/edge-functions';
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

for (const name of FUNCTIONS) {
  const entry = path.resolve('supabase/functions', name, 'index.ts');
  if (!fs.existsSync(entry)) {
    console.warn(`skip ${name}: no index.ts`);
    continue;
  }
  await build({
    entryPoints: [entry],
    outfile: path.join(OUT, `${name}.ts`),
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    // Deno resolves these at runtime; keep them as import statements.
    external: ['https://*', 'jsr:*', 'npm:*', 'node:*'],
    banner: {
      js: `// AUTO-GENERATED by scripts/bundle-edge-functions.mjs — do not edit by hand.\n// Paste this whole file as the Edge Function body in the Supabase dashboard.\n`,
    },
    logLevel: 'warning',
  });
  const size = fs.statSync(path.join(OUT, `${name}.ts`)).size;
  console.log(`bundled ${name}.ts (${(size / 1024).toFixed(1)} KB)`);
}

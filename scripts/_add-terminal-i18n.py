def deep_merge(base, over):
    out = dict(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = v
    return out


def render(obj, indent=2):
    lines = []
    pad = "  " * indent
    for k, v in obj.items():
        if isinstance(v, dict):
            lines.append(f"{pad}{k}: {{")
            lines.append(render(v, indent + 1))
            lines.append(f"{pad}}},")
        else:
            escaped = v.replace("\\", "\\\\").replace('"', '\\"')
            lines.append(f'{pad}{k}: "{escaped}",')
    return "\n".join(lines)


def main():
    with open(PATH, "r", encoding="utf-8") as f:
        src = f.read()

    if "\n  terminal: {" in src:
        print("terminal namespace already present; nothing to do")
        return 0

    # Insert the terminal namespace right before `nav: {` in each locale.
    for loc in LOCALES:
        merged = deep_merge(TERMINAL_EN, TERMINAL.get(loc, {}))
        block = "  terminal: {\n" + render(merged) + "\n  },\n\n"
        marker = f"const {loc}Translation = {{"
        start = src.index(marker)
        nav_idx = src.index("  nav: {", start)
        src = src[:nav_idx] + block + src[nav_idx:]

    # Insert the dashboard extra keys right after each `  dashboard: {` line.
    for loc in LOCALES:
        marker = f"const {loc}Translation = {{"
        start = src.index(marker)
        dash_idx = src.index("  dashboard: {", start)
        insert_at = dash_idx + len("  dashboard: {")
        extra = DASHBOARD_EXTRA[loc]
        lines = "".join(
            f'\n    {k}: "{v.replace(chr(92), chr(92)*2).replace(chr(34), chr(92)+chr(34))}",'
            for k, v in extra.items()
        )
        src = src[:insert_at] + lines + src[insert_at:]

    with open(PATH, "w", encoding="utf-8") as f:
        f.write(src)
    print("inserted terminal namespace + dashboard keys into all 11 locales")
    return 0



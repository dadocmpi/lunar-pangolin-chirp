KEY_ORDER = list(T["en"].keys())

src = PATH.read_text(encoding="utf-8")
lines = src.split("\n")

starts = []
for loc in LOCALE_ORDER:
    needle = f"const {loc}Translation = "
    idx = next((i for i, l in enumerate(lines) if l.startswith(needle)), -1)
    if idx < 0:
        sys.exit(f"locale {loc} not found")
    starts.append((loc, idx))

added = 0
for loc, start in reversed(starts):
    next_start = next((s for l, s in starts if s > start), len(lines))
    if any("withdrawal: {" in lines[i] for i in range(start, next_start)):
        continue
    anchor = next(
        (i for i in range(start, next_start - 1) if lines[i].startswith(ANCHOR)),
        None,
    )
    if anchor is None:
        sys.exit(f"anchor not found in locale {loc}")
    vals = T[loc]
    block = ["    withdrawal: {"]
    for k in KEY_ORDER:
        v = vals[k].replace("\\", "\\\\").replace('"', '\\"')
        block.append(f'      {k}: "{v}",')
    block.append("    },")
    lines[anchor + 1:anchor + 1] = block
    added += 1

PATH.write_text("\n".join(lines), encoding="utf-8")
print(f"inserted withdrawal namespace into {added} locale(s)")
